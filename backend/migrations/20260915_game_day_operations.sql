CREATE TABLE IF NOT EXISTS game_readiness (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id INTEGER NOT NULL UNIQUE REFERENCES matches(id) ON DELETE CASCADE,
  venue_ready BOOLEAN NOT NULL DEFAULT FALSE,
  equipment_ready BOOLEAN NOT NULL DEFAULT FALSE,
  home_team_present BOOLEAN NOT NULL DEFAULT FALSE,
  away_team_present BOOLEAN NOT NULL DEFAULT FALSE,
  lineups_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
  officials_ready BOOLEAN NOT NULL DEFAULT FALSE,
  medical_ready BOOLEAN NOT NULL DEFAULT FALSE,
  notes VARCHAR(500),
  updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS game_incidents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
  incident_type VARCHAR(30) NOT NULL,
  severity VARCHAR(20) NOT NULL DEFAULT 'low',
  description VARCHAR(1000) NOT NULL,
  action_taken VARCHAR(1000),
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  reported_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  resolved_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  resolved_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS game_incidents_idx_match_status ON game_incidents(match_id,status);
